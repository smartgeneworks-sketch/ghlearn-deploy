/** Prints every API route (method and path) from the live Express router, grouped by area. Used for docs/API_ROUTES.md. */
import fs from 'node:fs';
process.env.JWT_ACCESS_SECRET ??= 'list-routes-placeholder-0123456789abcdef'; process.env.JWT_REFRESH_SECRET ??= 'list-routes-placeholder-fedcba9876543210';
const { createApp } = await import('../src/app.js');
const src = fs.readFileSync(new URL('../src/app.ts', import.meta.url), 'utf8');
const prefixes = [...new Set([...src.matchAll(/app\.use\('(\/api[^']*)'/g)].map((m) => m[1]))].sort((a, b) => b.length - a.length);
const out: [string, string][] = []; const app: any = createApp();
for (const l of app.router.stack) {
  if (l.route) { for (const m of Object.keys(l.route.methods)) out.push([m.toUpperCase(), l.route.path]); continue; }
  if (!l.handle?.stack) continue;
  const mount = prefixes.find((p) => { const r = l.matchers?.[0]?.(p); return r && r.path === p; })!;
  for (const s of l.handle.stack) if (s.route) for (const m of Object.keys(s.route.methods)) if (m !== '_all') out.push([m.toUpperCase(), mount + (s.route.path === '/' ? '' : s.route.path)]);
}
const area = (p: string) => p.split('/').slice(0, p.startsWith('/api/admin/') ? 4 : 3).join('/');
const groups = new Map<string, string[]>(); for (const [m, p] of out) { const a = area(p); groups.set(a, [...(groups.get(a) ?? []), `${m} ${p}`]); }
let md = `# API routes (generated)\n\nGenerated by \`npx tsx scripts/list-routes.ts\` (server) from the live Express router: **${out.length} routes**. Permissions and payloads: see API.md; the route-by-role matrix test (server/test/security.test.ts) walks the same list.\n`;
for (const [a, rs] of [...groups].sort()) md += `\n## ${a} (${rs.length})\n${rs.map((r) => `- \`${r}\``).join('\n')}\n`;
fs.writeFileSync(new URL('../../docs/API_ROUTES.md', import.meta.url), md); console.log(out.length, 'routes');
process.exit(0);
