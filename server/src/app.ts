import { teacherApplyRouter, teacherReviewRouter } from './routes/teacherApplications.js';
import { logger } from './lib/logger.js';
import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import crypto from 'node:crypto';
import mongoose from 'mongoose';
import { config } from './config.js';
import { sanitize, requireFeature } from './middleware/index.js';
import { csrfProtect, issueCsrf } from './middleware/csrf.js';
import { documentsRouter } from './routes/documents.js';
import { lessonsRouter } from './routes/lessons.js';
import { tutorRouter } from './routes/tutor.js';
import { publicSettingsRouter, settingsAdminRouter } from './routes/settings.js';
import { AppError, errorHandler, notFoundHandler } from './lib/errors.js';
import { authRouter } from './routes/auth.js';
import { accountRouter } from './routes/account.js';
import { adminSmsRouter, adminEmailRouter } from './routes/adminSms.js';
import { configRouter } from './routes/config.js';
import { studentRouter } from './routes/students.js';
import { questionsRouter } from './routes/questions.js';
import { gameDesignsRouter } from './routes/gameDesigns.js';
import { practiceRouter, gamesRouter, rewardsRouter, progressRouter, assessmentsRouter } from './routes/practice.js';
import { teacherRouter, offlineRouter, notificationsRouter } from './routes/teacher.js';
import { meetingsRouter } from './routes/meetings.js';
import { analyticsRouter } from './routes/analytics.js';
import './services/assess/generate.js';
import { adminRouter } from './routes/admin.js';
import { publicRouter } from './routes/public.js';
import { websiteAdminRouter } from './routes/website.js';
import { adminPanelRouter } from './routes/adminPanel.js';
import { adminUsersRouter } from './routes/adminUsers.js';
import { adminSchoolsRouter } from './routes/adminSchools.js';
import { adminClassesRouter } from './routes/adminClasses.js';
import { curriculumRouter } from './routes/curriculum.js';
import { curriculumLmsRouter } from './routes/curriculumLms.js';
import { jobsRouter } from './routes/jobs.js';
import { aiAdminRouter } from './routes/aiAdmin.js';
import { announcementsRouter } from './routes/announcements.js';
import { openapi } from './openapi.js';
import { aiStatus } from './services/ai.js';

export function createApp() {
  const app = express();
  app.set('trust proxy', 1);
  app.disable('x-powered-by');
  app.use((req, res, next) => { req.id = String(req.get('x-request-id') ?? '').replace(/[^\w.:-]/g, '').slice(0, 64) || crypto.randomUUID(); res.set('x-request-id', req.id); next(); });
  app.use(helmet());
  // Structured access log for server errors and slow requests only (JSON via pino; no bodies, no query strings).
  app.use((req, res, next) => { const t = process.hrtime.bigint(); res.on('finish', () => { const ms = Number(process.hrtime.bigint() - t) / 1e6;
    if (res.statusCode >= 500 || ms > 5000) logger[res.statusCode >= 500 ? 'error' : 'warn']({ requestId: req.id, method: req.method, path: req.path, status: res.statusCode, ms: Math.round(ms) }, res.statusCode >= 500 ? 'request failed' : 'slow request'); }); next(); });
  app.use(cors({ origin: config.corsOrigins, credentials: true, allowedHeaders: ['Content-Type', 'X-CSRF-Token', 'X-Request-Id', 'X-Idle-Ms'], maxAge: 7200 }));
  // System settings carry a logo (≤150 KB) and the terms and privacy texts, so that one route accepts a larger body.
  const json = express.json({ limit: '200kb' }), settingsJson = express.json({ limit: '360kb' });
  app.use((req, res, next) => (req.path === '/api/admin/settings' ? settingsJson : json)(req, res, next));
  app.use(cookieParser());
  app.use(sanitize);
  app.use('/api', rateLimit({ windowMs: 60_000, limit: config.NODE_ENV === 'test' ? 10_000 : 300, standardHeaders: 'draft-8', legacyHeaders: false,
    handler: (_q, _r, next) => next(new AppError(429, 'RATE_LIMITED', 'Too many requests')) }));
  // Basic CSRF defence for cookie auth: state-changing requests must be JSON (blocks simple cross-site form posts).
  app.use('/api', (req, _res, next) => {
    if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(req.method) && req.headers['content-length'] !== '0' && req.body && !req.is('application/json') && !req.is('multipart/form-data') && req.headers['content-type'])
      return next(new AppError(415, 'UNSUPPORTED_MEDIA', 'Use application/json'));
    next();
  });
  app.get('/api/auth/csrf', (_req, res) => res.json({ csrfToken: issueCsrf(res) }));
  app.use('/api', csrfProtect);
  app.get('/api/health', (_req, res) => res.json({ ok: true, db: mongoose.connection.readyState === 1, ai: aiStatus() }));
  app.get('/api/docs/openapi.json', (_req, res) => res.json(openapi));
  app.use('/api/auth', authRouter);
  app.use('/api/account', accountRouter);
  app.use('/api/config', configRouter);
  app.use('/api/settings', publicSettingsRouter);
  app.use('/api/public/teacher-applications', teacherApplyRouter);
  app.use('/api/public', publicRouter);
  app.use('/api/admin', teacherReviewRouter);
  app.use('/api/admin/website', websiteAdminRouter);
  app.use('/api/admin/settings', settingsAdminRouter);
  app.use('/api/admin/ai', aiAdminRouter);
  app.use('/api/admin/sms', adminSmsRouter);
  app.use('/api/admin/email', adminEmailRouter);
  app.use('/api/admin', adminPanelRouter);
  app.use('/api/admin', adminUsersRouter);
  app.use('/api/admin', adminSchoolsRouter);
  app.use('/api/admin', adminClassesRouter);
  app.use('/api/curriculum', curriculumRouter);
  app.use('/api/curriculum-lms', curriculumLmsRouter);
  app.use('/api/jobs', jobsRouter);
  app.use('/api/admin', adminRouter);
  app.use('/api/documents', documentsRouter);
  app.use('/api/lessons', lessonsRouter);
  app.use('/api/tutor', requireFeature('tutor'), tutorRouter);
  app.use('/api/questions', questionsRouter);
  app.use('/api/game-designs', gameDesignsRouter);
  app.use('/api/practice', requireFeature('practice'), practiceRouter);
  app.use('/api/games', requireFeature('games'), gamesRouter);
  app.use('/api/rewards', rewardsRouter);
  app.use('/api/progress', progressRouter);
  app.use('/api/assessments', requireFeature('assessments'), assessmentsRouter);
  app.use('/api/teacher', teacherRouter);
  app.use('/api/offline', offlineRouter);
  app.use('/api/notifications', notificationsRouter);
  app.use('/api/announcements', announcementsRouter);
  app.use('/api/analytics', analyticsRouter);
  app.use('/api/meetings', requireFeature('meetings'), meetingsRouter);
  app.use('/api', studentRouter);
  app.use(notFoundHandler);
  app.use(errorHandler);
  return app;
}
